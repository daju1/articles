// ============== dislocation_rings_v3_vector.h ==============
#ifndef DISLOCATION_RINGS_V3_VECTOR_H
#define DISLOCATION_RINGS_V3_VECTOR_H
/* =====================================================================
   v3-vector: ПАРА СКОЛЬЗЯЩИХ (GLIDE) дислокационных колец с ВЕКТОРНЫМ
   вектором Бюргерса. Магнитный заряд q_m = РАЗРЫВ Бюргерса Δb в особой
   точке (размерно корректно: [q_m]=[b]=длина; см.
   NOTE_v3_glide_magnetic_charge_dimensional.md, 24 окт 2026).

   ГЕОМЕТРИЯ (уточнено пользователем 24 окт 2026):
   • Два кольца радиуса a, плоскости НЕПОДВИЖНЫ, разнесены по оси z (±d/2).
   • "Прецессия" = бег ОСОБОЙ ТОЧКИ по кольцу с частотой ω (НЕ шатание
     плоскостей).
   • Особые точки в ПРОТИВОФАЗЕ (Δφ=π).
   • Вектор Бюргерса b В ПЛОСКОСТИ кольца (glide), ВЕКТОРНЫЙ (не скаляр).
   • Магнитный заряд = Δb (разрыв в особой точке), противоположные знаки
     на двух кольцах (±q_m), e⁻=интерстициал/+, e⁺=вакансия/−.

   РЕЗУЛЬТАТЫ (численно, 24 окт 2026):
   • Осевой диполь p_z=q_m·d=const; поперечный p_xy прецессирует с ω.
   • μ_z/J_z=-0.5 → классическое g=1 (НЕ g=2; g=2 требует спинора Дирака).
   • Масса из самодействия m~μ_shear·q_m²·a/c²; тогда g~c²/(μ_shear q_m a).
   • Стабильность: вихревой барьер (ωa/c)²/d² vs притяжение 1/d → минимум d_eq.
   • e⁻/e⁺: два независимых знака (прецессия ω + знак Δb), переворот вместе (CP).
   • Аннигиляция: рекомбинация Френкеля, b(e⁻)+b(e⁺)=0 → идеальная решётка.
   ===================================================================== */

typedef struct {
    double center[3];      /* центр кольца */
    double a;              /* радиус */
    double omega;          /* частота бега особой точки */
    double phase0;         /* нач. фаза (противофаза: 0 и π) */
    double b_vec[3];       /* ВЕКТОР Бюргерса (в плоскости кольца, glide) */
    double delta_b;        /* q_m = РАЗРЫВ Бюргерса в особой точке [длина] */
    double mu_shear, nu;   /* упругие постоянные */
    int    n_elem;
} RingV;

/* Положение/скорость особой точки на кольце в момент t. */
void special_point(const RingV *R, double t, double pos[3], double vel[3]);
/* Мгновенный дипольный момент пары (осевой const + прецессирующий поперечный). */
void pair_dipole(const RingV *top, const RingV *bot, double t, double p_out[3]);
/* Магнитный момент μ и момент импульса J пары (усреднённые). */
void pair_moments(const RingV *top, const RingV *bot, double c,
                  double mu_out[3], double J_out[3]);
/* Физический магнитный момент пары = ДИПОЛЬНЫЙ q_m·d (токовый μ_z=0). */
double pair_magnetic_dipole(const RingV *top, const RingV *bot);
/* Масса из самодействия петли: m = k·μ_shear·q_m²·a/c². */
double loop_mass(const RingV *R, double c, double k);
/* Энергия пары E(d) с вихревым барьером; для поиска равновесия. */
double pair_energy(double d, double Jcons, double m_eff, double A); /* центробежный барьер */
/* Суммарный Бюргерс пары (=0 при аннигиляции Френкеля). */
void total_burgers(const RingV *top, const RingV *bot, double out[3]);

#endif

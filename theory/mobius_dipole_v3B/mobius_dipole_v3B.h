// ============== mobius_dipole_v3B.h ==============
#ifndef MOBIUS_DIPOLE_V3B_H
#define MOBIUS_DIPOLE_V3B_H
/* =====================================================================
   ВЕТКА B: прецессирующий диполь из ПАРЫ МЁБИУС-колец.
   N-полюс = мёбиус-кольцо (твист +θ/2), S-полюс = анти-мёбиус (твист -θ/2).
   Параллельна ветке A (dislocation_rings_v3_vector, пара обычных колец).

   ГЕОМЕТРИЯ (24 окт 2026):
   • Два мёбиус-кольца радиуса a, плоскости неподвижны, разнесены по z (±d/2).
   • Каждое несёт ОДНУ особую точку (заряд q_m=Δb), бегущую с ω (прецессия).
   • Особые точки в противофазе (Δφ=π), как в ветке A.
   • Мёбиус: знак Бюргерса твистуется cos(θ/2), период 4π. Анти-мёбиус: cos(-θ/2).

   РЕЗУЛЬТАТЫ (численно, 24 окт 2026):
   • Магнитный диполь q_m·d — ЕСТЬ (пара мёбиусов, как пара колец).
   • Период ПАРЫ = 4π → ФЕРМИОН (спин-½)! В отличие от glide-пары (2π, бозон).
   • Защита прецессией: ω=0 → аннигиляция (общий критерий с веткой A).
   • Аннигиляция ДВУХСТУПЕНЧАТАЯ: сначала разворот твиста (барьер ∫(db/dθ)²≈1.57),
     потом гашение Бюргерсов (в отличие от одноступенчатой glide).
   • КАНДИДАТ НА ЭЛЕКТРОН (фермион), тогда как glide-пара — бозон.
   ===================================================================== */

typedef struct {
    double center[3];
    double a, omega, phase0;
    double delta_b;        /* q_m = разрыв Бюргерса [длина] */
    int    chirality;      /* +1 мёбиус (N), -1 анти-мёбиус (S) */
    double mu_shear, nu;
    int    n_elem;
} MobiusRing;

/* Положение/скорость особой точки. */
void mb_special_point(const MobiusRing *R, double t, double pos[3], double vel[3]);
/* Знак Бюргерса с твистом cos(chirality·θ/2) (период 4π). */
double mb_burgers_sign(const MobiusRing *R, double t);
/* Период пары (4π для мёбиус-диполя) — возврат конфигурации. */
double mb_pair_period(const MobiusRing *N, const MobiusRing *S);
/* Магнитный дипольный момент пары = q_m·d (статический, осевой). */
double mb_pair_magnetic_dipole(const MobiusRing *N, const MobiusRing *S);
/* Энергия пары с центробежным барьером (защита прецессией). */
double mb_pair_energy(double d, double Jcons, double m_eff, double A);
/* Барьер разворота твиста при аннигиляции (двухступенчатость). */
double mb_twist_unwind_barrier(const MobiusRing *R);

#endif

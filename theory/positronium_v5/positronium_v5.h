// ===================== positronium_v5.h =====================
#ifndef POSITRONIUM_V5_H
#define POSITRONIUM_V5_H
/* =====================================================================
   positronium_v5.h  — модель электрона как ДИПОЛЯ ИЗ ДВУХ ПРЕЦЕССИРУЮЩИХ
   МАГНИТНЫХ МОНОПОЛЕЙ ДИРАКА. Написано с нуля (не наследует кольца v1-v4).
   ---------------------------------------------------------------------
   ОНТОЛОГИЯ (ключевое):
   • Фундаментальны ТОЛЬКО магнитные монополи Дирака ±q_m.
   • Электрон = связанная пара (+q_m, -q_m), прецессирующая с частотой ω
     на радиусе a (прецессионная "гантель").
   • Электрического заряда e КАК ТАКОВОГО НЕТ: кулоновское взаимодействие
     ВЫВОДИТСЯ из взаимодействия прецессирующих диполей.
   • Поле монополя строится по дислокационной T(3)-теории Лазара
     (central ~ кулон-аналог, vortex ~ аналог B / сила Пича-Кёлера),
     ВСЕГДА запаздывающее и с излучением. Мгновенна только поправка Ферми.

   ПЯТЬ ЗАДАЧ (режимы расчёта, см. Task ниже):
   1. STABILITY_SELF    — устойчивость фермиона от самоаннигиляции пары
                          +q_m,-q_m благодаря прецессии (центробежный барьер).
   2. COULOMB_PAIR      — кулоновское взаимодействие двух фермионов
                          (эффективный 1/R со знаком от разности фаз).
   3. GRAVITY_PAIR      — гравитационное взаимодействие (изотропный
                          знаконезависимый член σ~⟨W²⟩/c², всегда притяжение).
   4. EXCHANGE          — обменное взаимодействие (член cos2Δφ).
   5. BOHR_ORBIT        — устойчивость боровской орбиты монополей внутри
                          фермиона (резонанс стоячей волны nλ=2πa, безызлуч.).

   ВЫВОД e (режим EffChargeMode): не фиксируем заранее —
     ECHARGE_DARWIN  : эффективный заряд из скоростного (v/c) члена поля
                       прецессирующего диполя (дарвиновское разложение);
     ECHARGE_FERMI   : из фермиевской поправки к границе действия (вариация B).
   Код поддерживает ОБА, чтобы сравнить численно.
   ===================================================================== */

typedef enum { TASK_STABILITY_SELF=0, TASK_COULOMB_PAIR=1, TASK_GRAVITY_PAIR=2,
               TASK_EXCHANGE=3, TASK_BOHR_ORBIT=4 } Task;
typedef enum { ECHARGE_DARWIN=0, ECHARGE_FERMI=1 } EffChargeMode;

/* Один магнитный монополь Дирака как член прецессирующей пары. */
typedef struct {
    double center[3];    /* центр прецессии (положение фермиона) */
    double e1[3], e2[3];  /* базис плоскости прецессии (орты) */
    double a;             /* радиус прецессии (полуразнос пары) */
    double omega;          /* частота прецессии */
    double phase0;          /* начальная фаза */
    double qm;              /* магнитный заряд монополя (|q_m|) */
    int    sign;             /* +1 / -1: это +q_m или -q_m партнёр */
    /* упругие постоянные среды (Лазар): */
    double mu, nu, gamma;    /* сдвиг, Пуассон, асимметрия T(3) */
} Monopole;

/* Фермион = пара монополей (+ и -) с общим центром и прецессией. */
typedef struct { Monopole plus, minus; } Fermion;

/* --- API пяти задач --- */

/* 1. Полная энергия самодействия фермиона как функция радиуса a:
   E(a) = E_annih(a) [стягивание пары, ~ -1/a] + E_prec(a) [прецессия,
   центробежный барьер ~ +a·ω²] + натяжение. Минимум при a_eq>0 = устойчивость. */
double fermion_self_energy(const Fermion *F, double a, double *E_attr, double *E_prec);
double fermion_equilibrium_radius(const Fermion *F, double amin, double amax,
                                  int n, int *stable);

/* 2-4. Взаимодействие двух фермионов в момент t; task выбирает канал. */
void fermion_pair_force(const Fermion *F1, const Fermion *F2, double t, double c,
                        Task task, EffChargeMode emode, double out_force[3]);

/* 5. Проверка боровского резонанса: возвращает |отклонение| от условия
   nλ=2πa для моды n (0 = точный резонанс = безызлучательная орбита). */
double bohr_orbit_residual(const Fermion *F, double c, int n);

#endif /* POSITRONIUM_V5_H */

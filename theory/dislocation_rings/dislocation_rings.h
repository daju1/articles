// ===================== dislocation_rings.h =====================
#ifndef DISLOCATION_RINGS_H
#define DISLOCATION_RINGS_H

/* =====================================================================
   dislocation_rings.h  (v2 -- два режима "мыльной плёнки")
   ---------------------------------------------------------------------
   БИБЛИОТЕКА ДИНАМИКИ КОЛЬЦА И ДИПОЛЯ ИЗ ДВУХ КОЛЕЦ
   в формулах калибровочной теории дислокаций Кадича-Эделена / Лазара,
   строго изоморфной электродинамике (Lazar 2010, Table I;
   Braginsky 2016/2018).

       B (magnetic field strength)  <->  T^a  (плотность дислокаций)
       E (electric field strength)  <->  I^a  (ток дислокаций)
       H (magnetic excitation)      <->  H_a  (псевдомоментное напряжение)
       D (electric excitation)      <->  D_a  (поток дислокационного импульса)
       Lorentz force f=qE+qv x B    <->  сила на поток импульса (Пич-Келлер)

   =====================================================================
   КЛЮЧЕВОЕ РАЗГРАНИЧЕНИЕ УРОВНЕЙ (по вашему явному указанию):
   =====================================================================
   1) САМО ПОЛЕ (central + vortex часть, аналог Льенара-Вихерта) --
      ВСЕГДА запаздывающее/досветовое. Это отдельный физический уровень
      "волны/поля", который не смешивается с динамикой плёнки.
   2) ПОПРАВКА ФЕРМИ (наклон плёнки) -- это то место, где выбор режима
      имеет физический смысл. Здесь реализовано ДВА режима:

   FERMI_PLAIN -- одиночная формула Ферми БЕЗ полусуммы и без вклада
       других мировых трубок: (1 + a_own . r / c^2), где a_own --
       собственное (запаздывающее) ускорение ИСТОЧНИКА (Fermi 1923).

   FERMI_FILM_RETARDED -- "мейнстримная" версия обобщения на N трубок:
       дополнительный наклон плёнки собирается из ускорений ВСЕХ
       остальных элементов конфигурации, взятых в тот же ЗАПАЗДЫВАЮЩИЙ
       момент t', что и главный источник. То есть плёнка "узнаёт" о
       состоянии других трубок только через то, что успело дойти со
       скоростью c -- ПРИЧИННАЯ, светового-конуса версия. Это то, что
       получилось бы, если пытаться встроить многотельную поправку
       Ферми в стандартный запаздывающий формализм поля.

   FERMI_FILM_INSTANT -- ВАША версия: мгновенная нелокальная плёнка.
       Дополнительный наклон собирается из ускорений ВСЕХ остальных
       элементов, взятых в момент t_field -- то есть ОДНОВРЕМЕННО (в
       лабораторной системе отсчета) с точкой наблюдения, а НЕ в
       запаздывающий момент. Плёнка мгновенно минимизируется для "уже
       заданной" (одновременной) конфигурации всех мировых трубок --
       именно так, как явно описано в диалоге: "динамика плёнки --
       мгновенная... не эволюционирует во времени как волна, а
       мгновенно находит глобальный минимум функционала площади для
       данной конфигурации", в отличие от "динамики полей", которая
       остаётся досветовой.

   И в FILM_RETARDED, и в FILM_INSTANT интерполяция ускорений сделана
   ВЗВЕШЕННОЙ ПО ОБРАТНОМУ РАССТОЯНИЮ -- обобщение принципа
   интерполяции, строго доказанного для ДВУХ трубок, на N трубок.
   Это ЭВРИСТИЧЕСКИЙ АНЗАЦ в обоих случаях: строгий вывод из PDE
   минимальной гиперповерхности для N тел не проведён, различие между
   двумя режимами -- только в ТОМ, В КАКОЙ МОМЕНТ ВРЕМЕНИ берутся
   ускорения "чужих" трубок (запаздывающий vs одновременный).

   =====================================================================
   РЕЗУЛЬТАТЫ ПРОВЕРОК (см. чат для полных таблиц)
   =====================================================================
   (A) Взаимодействие ДВУХ ФЕРМИОНОВ (диполь-диполь, суммарный заряд
       каждого = 0): во всех трёх режимах сила УБЫВАЕТ с расстоянием
       без расходимости (проверено до R=160 радиусов). FILM_RETARDED и
       FILM_INSTANT дают близкие, но не идентичные значения к PLAIN.

   (B) Одно ЗАРЯЖЕННОЕ кольцо (ненейтральный "монополь") на больших R:
       поправка Ферми РАСХОДИТСЯ во всех трёх режимах -- это известная
       фундаментальная проблема самой формулы (1+a.R/c^2) для
       изолированного ускоряющегося заряда, а не дефект конкретного
       режима. FILM-режимы не предназначены и не должны магическим
       образом устранять эту базовую особенность одиночного заряда.

   (C) ВНУТРЕННЯЯ УСТОЙЧИВОСТЬ ОДНОГО ФЕРМИОНА (сила между кольцом N и
       кольцом S ОДНОГО диполя как функция разноса d, при коаксиальной
       геометрии одинакового радиуса a и общей omega): во ВСЕХ трёх
       режимах и на всём диапазоне d/a in [0.1, 3.0], omega in
       [0.1, 0.7] -- сила ЧИСТО ПРИТЯГИВАЮЩАЯ, равновесной точки
       (перехода через ноль) НЕ НАЙДЕНО. Это означает, что простая
       коаксиальная геометрия "два кольца разного знака, разнесённые
       вдоль оси" НЕ самостабилизируется в этой модели -- нужен
       дополнительный механизм (отталкивающее ядро от собственной
       энергии дефекта, иная -- не коаксиальная -- геометрия, или
       квантовое условие), которого в данной реализации НЕТ. Это
       ОТКРЫТЫЙ ВОПРОС, а не решённая задача устойчивости фермиона.
   ===================================================================== */

typedef enum {
    FERMI_PLAIN         = 0,  /* одиночная формула Ферми, без плёнки от др. трубок */
    FERMI_FILM_RETARDED = 1,  /* плёнка через запаздывающие ускорения (причинная) */
    FERMI_FILM_INSTANT  = 2,  /* плёнка через одновременные ускорения (ваша теория) */
    FERMI_NONE          = 3   /* без поправки Ферми вообще (для отладки) */
} FermiMode;

/* Конфигурация одного кольца ("мировая трубка"-континуум) */
typedef struct {
    double center[3];      /* центр кольца */
    double e1[3];           /* базисный вектор плоскости кольца (единичный) */
    double e2[3];           /* второй базисный вектор (единичный, ортогонален e1) */
    double radius;           /* радиус кольца a */
    double omega;             /* угловая скорость вращения элементов по кольцу */
    double phase0;             /* начальная фаза (относительный поворот кольца) */
    double total_charge;       /* суммарный "дислокационный заряд" T0 (аналог g) */
    int    n_elem;              /* число дискретных элементов дискретизации */
    int    charge_sign;          /* +1 или -1: знак элементов (для диполя: N/S) */
} RingConfig;

/* Сила взаимодействия между произвольным набором "полевых" колец
   (field_rings) и "источниковых" колец (source_rings) в момент t.

   ИСПОЛЬЗОВАНИЕ ДЛЯ ДВУХ РАЗНЫХ ЗАДАЧ:
   - Взаимодействие ДВУХ ФЕРМИОНОВ: field_rings = диполь A (2 кольца),
     source_rings = диполь B (2 кольца), центры разнесены на R.
   - Устойчивость ОДНОГО ФЕРМИОНА: field_rings = кольцо N этого же
     диполя (1 кольцо), source_rings = кольцо S этого же диполя
     (1 кольцо), оба -- часть ОДНОГО физического объекта.
   Функция не различает эти случаи структурно -- разница только в том,
   какие RingConfig ей передают.

   mode_int: см. FermiMode.
   c: скорость света (в выбранных единицах, обычно c=1).
   out_force[3]: результирующая сила (central + vortex часть). */
void compute_ring_dipole_force(
    const RingConfig *field_rings, int n_field_rings,
    const RingConfig *source_rings, int n_source_rings,
    double t, double c, int mode_int,
    double out_force[3]);

#endif /* DISLOCATION_RINGS_H */